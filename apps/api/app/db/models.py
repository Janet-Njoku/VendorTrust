"""SQLAlchemy 2 models for the Phase 1.3 tables (schema `vt`).

The migrations are hand-written SQL (RLS, policies and grants cannot be autogenerated); these
models describe the same tables for the application, and a test compares them with the migrated
database so the two cannot drift apart.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from decimal import Decimal
from typing import Any

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    ForeignKey,
    ForeignKeyConstraint,
    Identity,
    Index,
    MetaData,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, TIMESTAMP, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

SCHEMA = "vt"
ORG_STATUSES = ("active", "suspended")
USER_STATUSES = ("active", "disabled")
VENDOR_STATUSES = ("active", "archived")
MEMBERSHIP_STATUSES = ("active", "suspended", "revoked")
ROLES = ("org_admin", "analyst", "reviewer", "auditor", "vendor_user")

metadata = MetaData(schema=SCHEMA)


class Base(DeclarativeBase):
    metadata = metadata


def _in(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN ({', '.join(repr(v) for v in values)})"


def _uuid_pk(default: bool = True) -> Mapped[uuid.UUID]:
    return mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=text("gen_random_uuid()") if default else None,
    )


def _created() -> Mapped[datetime]:
    return mapped_column(TIMESTAMP(timezone=True), nullable=False, server_default=func.now())


class Organization(Base):
    __tablename__ = "organizations"
    __table_args__ = (
        CheckConstraint("length(btrim(name)) BETWEEN 1 AND 200", name="ck_organizations_name"),
        CheckConstraint(_in("status", ORG_STATUSES), name="ck_organizations_status"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    name: Mapped[str] = mapped_column(Text, nullable=False)
    status: Mapped[str] = mapped_column(Text, nullable=False, server_default="active")
    created_at: Mapped[datetime] = _created()
    updated_at: Mapped[datetime] = _created()


class AppUser(Base):
    """A person known to the application. `id` is the Supabase Auth `sub` (never generated here)."""

    __tablename__ = "app_users"
    __table_args__ = (
        CheckConstraint("length(email) BETWEEN 3 AND 320", name="ck_app_users_email"),
        CheckConstraint(
            "display_name IS NULL OR length(display_name) <= 200", name="ck_app_users_display_name"
        ),
        CheckConstraint(_in("status", USER_STATUSES), name="ck_app_users_status"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk(default=False)
    email: Mapped[str] = mapped_column(Text, nullable=False)
    display_name: Mapped[str | None] = mapped_column(Text)
    status: Mapped[str] = mapped_column(Text, nullable=False, server_default="active")
    created_at: Mapped[datetime] = _created()
    updated_at: Mapped[datetime] = _created()


