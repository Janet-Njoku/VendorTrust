class QuestionnaireVersion(Base):
    """Immutable once published: questions, options, weights and thresholds are frozen."""

    __tablename__ = "questionnaire_versions"
    __table_args__ = (
        ForeignKeyConstraint(
            ["org_id", "template_id"],
            ["questionnaire_templates.org_id", "questionnaire_templates.id"],
            name="fk_questionnaire_versions_template",
        ),
        UniqueConstraint("org_id", "id", name="uq_questionnaire_versions_org_id_id"),
        UniqueConstraint(
            "template_id", "version_number", name="uq_questionnaire_versions_template_number"
        ),
        CheckConstraint("version_number >= 1", name="ck_questionnaire_versions_number"),
        CheckConstraint(_in("status", VERSION_STATUSES), name="ck_questionnaire_versions_status"),
        CheckConstraint(
            "0 < low_max AND low_max < medium_max AND medium_max < high_max AND high_max <= 100",
            name="ck_questionnaire_versions_thresholds",
        ),
        CheckConstraint(
            "status <> 'published' OR published_at IS NOT NULL",
            name="ck_questionnaire_versions_published",
        ),
        Index(
            "uq_questionnaire_versions_one_draft",
            "template_id",
            unique=True,
            postgresql_where=text("status = 'draft'"),
        ),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    org_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    template_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    version_number: Mapped[int] = mapped_column(nullable=False)
    status: Mapped[str] = mapped_column(Text, nullable=False, server_default="draft")
    low_max: Mapped[int] = mapped_column(nullable=False, server_default="25")
    medium_max: Mapped[int] = mapped_column(nullable=False, server_default="50")
    high_max: Mapped[int] = mapped_column(nullable=False, server_default="75")
    published_at: Mapped[datetime | None] = mapped_column(TIMESTAMP(timezone=True))
    created_at: Mapped[datetime] = _created()
    updated_at: Mapped[datetime] = _created()


