class Assessment(Base):
    __tablename__ = "assessments"
    __table_args__ = (
        ForeignKeyConstraint(
            ["org_id", "vendor_id"], ["vendors.org_id", "vendors.id"], name="fk_assessments_vendor"
        ),
        ForeignKeyConstraint(
            ["org_id", "version_id"],
            ["questionnaire_versions.org_id", "questionnaire_versions.id"],
            name="fk_assessments_version",
        ),
        UniqueConstraint("org_id", "id", name="uq_assessments_org_id_id"),
        CheckConstraint(_in("status", ASSESSMENT_STATUSES), name="ck_assessments_status"),
        CheckConstraint("score IS NULL OR score BETWEEN 0 AND 100", name="ck_assessments_score"),
        CheckConstraint(
            "risk_level IS NULL OR " + _in("risk_level", RISK_LEVELS),
            name="ck_assessments_risk_level",
        ),
        CheckConstraint(
            "(status = 'scored' AND score IS NOT NULL AND risk_level IS NOT NULL "
            "AND scored_at IS NOT NULL AND scored_by IS NOT NULL AND breakdown IS NOT NULL) "
            "OR (status = 'in_progress' AND score IS NULL AND risk_level IS NULL "
            "AND scored_at IS NULL AND scored_by IS NULL AND breakdown IS NULL)",
            name="ck_assessments_result",
        ),
        Index("ix_assessments_org_id_vendor_id", "org_id", "vendor_id"),
        Index("ix_assessments_version_id", "version_id"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    org_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    vendor_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    version_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    status: Mapped[str] = mapped_column(Text, nullable=False, server_default="in_progress")
    created_by: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("app_users.id", name="fk_assessments_created_by"),
        nullable=False,
    )
    score: Mapped[Decimal | None] = mapped_column(Numeric(4, 1))
    risk_level: Mapped[str | None] = mapped_column(Text)
    scored_at: Mapped[datetime | None] = mapped_column(TIMESTAMP(timezone=True))
    scored_by: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("app_users.id", name="fk_assessments_scored_by")
    )
    breakdown: Mapped[dict[str, Any] | None] = mapped_column(JSONB)
    created_at: Mapped[datetime] = _created()
    updated_at: Mapped[datetime] = _created()


